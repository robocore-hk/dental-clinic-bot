"""Builds the dashboard, embeds it into the Worker (server/src/static.ts) and bundles the Worker to server/dist/index.js."""
import base64, json, mimetypes, os, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dash = os.path.join(root, 'dashboard'); srv = os.path.join(root, 'server')
if '--skip-dash' not in sys.argv:
    subprocess.run(['npm', 'run', 'build'], cwd=dash, check=True)
MIME = {'.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.html': 'text/html; charset=utf-8', '.svg': 'image/svg+xml', '.ttf': 'font/ttf', '.png': 'image/png', '.ico': 'image/x-icon', '.json': 'application/json'}
files = {}
d = os.path.join(dash, 'dist')
for base, _, names in os.walk(d):
    for n in names:
        p = os.path.join(base, n); rel = '/' + os.path.relpath(p, d).replace(os.sep, '/')
        files[rel] = [MIME.get(os.path.splitext(n)[1], mimetypes.guess_type(n)[0] or 'application/octet-stream'), base64.b64encode(open(p, 'rb').read()).decode()]
open(os.path.join(srv, 'src', 'static.ts'), 'w').write('// Generated by tools/build.py\nexport const DASHBOARD: Record<string, [string, string]> = ' + json.dumps(files) + ';\n')
subprocess.run(['npx', 'tsc', '--noEmit', '-p', '.'], cwd=srv, check=True)
os.makedirs(os.path.join(srv, 'dist'), exist_ok=True)
subprocess.run(['npx', 'esbuild', 'src/index.ts', '--bundle', '--format=esm', '--minify', '--outfile=dist/index.js'], cwd=srv, check=True)
print('built', len(files), 'files', os.path.getsize(os.path.join(srv, 'dist', 'index.js')), 'bytes')
